import DOMPurify from "dompurify";
import { diagramAllowed } from "./diagram-policy.js";
export { diagramAllowed } from "./diagram-policy.js";
let renderer;
let sequence = 0;
export const mermaidConfig = Object.freeze({
	startOnLoad: false,
	securityLevel: "strict",
	suppressErrorRendering: true,
	maxTextSize: 12000,
	maxEdges: 100,
	htmlLabels: false,
	flowchart: { htmlLabels: false },
	secure: [
		"secure",
		"securityLevel",
		"startOnLoad",
		"maxTextSize",
		"maxEdges",
		"suppressErrorRendering",
		"htmlLabels",
		"flowchart",
		"theme",
		"themeVariables",
		"themeCSS",
		"fontFamily",
		"altFontFamily",
		"dompurifyConfig",
	],
});
export async function renderDiagram(code, target, dark) {
	if (!diagramAllowed(code))
		throw new Error(
			"只支援純文字矩形節點與箭頭的 Flowchart；設定、樣式、互動及未知語法已拒絕。",
		);
	renderer ||= import("mermaid").then((m) => m.default);
	const mermaid = await renderer;
	const palette = getComputedStyle(document.body);
	const color = (token) => palette.getPropertyValue(`--ks-${token}`).trim();
	mermaid.initialize({
		...mermaidConfig,
		theme: "base",
		fontFamily: palette.getPropertyValue("--ks-font").trim(),
		themeVariables: {
			primaryColor: color("soft"),
			primaryTextColor: color("text"),
			primaryBorderColor: color("link"),
			lineColor: color("muted"),
			background: color("surface"),
		},
	});
	await mermaid.parse(code);
	const id = `ks-diagram-${++sequence}`;
	// Explicit detached work area is removed even when Mermaid parsing fails.
	const workspace = document.createElement("div");
	workspace.className = "ks-diagram-workspace";
	document.body.append(workspace);
	try {
		const { svg } = await mermaid.render(id, code, workspace);
		const clean = DOMPurify.sanitize(svg, {
			USE_PROFILES: { svg: true, svgFilters: true },
			FORBID_TAGS: ["foreignObject", "a", "image", "use", "script"],
			FORBID_ATTR: ["href", "xlink:href", "tabindex"],
			RETURN_DOM_FRAGMENT: true,
		});
		const graphic = clean.querySelector("svg");
		if (!graphic) throw new Error("沒有可顯示的圖表。");
		// CSS generated by the pinned library is confined to an opaque sandbox.
		// Also disallow all CSS network primitives, even inside the sandbox.
		for (const style of graphic.querySelectorAll("style")) {
			style.textContent = style.textContent.replace(
				/@import[^;]+;|url\((?!\s*['"]?#)[^)]*\)/gi,
				"",
			);
		}
		target.replaceChildren();
		const frame = document.createElement("iframe");
		frame.setAttribute("sandbox", "");
		frame.title = "流程圖，圖內可捲動；文字替代與原碼位於圖表旁";
		frame.className = "ks-diagram-frame";
		const [, , graphicWidth, graphicHeight] = graphic
			.getAttribute("viewBox")
			.split(/\s+/)
			.map(Number);
		if (!(graphicWidth > 0 && graphicHeight > 0))
			throw new Error("圖表尺寸無效。");
		let zoom = 100;
		const draw = () => {
			frame.setAttribute("aria-busy", "true");
			frame.onload = () => frame.setAttribute("aria-busy", "false");
			frame.style.aspectRatio = `${graphicWidth} / ${(graphicHeight * zoom) / 100}`;
			graphic.removeAttribute("width");
			graphic.removeAttribute("height");
			graphic.style.cssText = `width:${zoom}%;max-width:none;height:auto;display:block`;
			frame.srcdoc = `<!doctype html><html lang="zh-Hant"><meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; base-uri 'none'; form-action 'none'"><style>body{margin:0;background:${color("surface")};color-scheme:${dark ? "dark" : "light"}}div{overflow:auto;height:100vh}div:focus-visible{outline:3px solid ${color("focus")};outline-offset:-3px}</style><div tabindex="0" role="region" aria-label="圖表，可用方向鍵捲動">${graphic.outerHTML}</div></html>`;
		};
		const controls = document.createElement("div");
		controls.className = "ks-diagram-controls";
		const output = document.createElement("span");
		output.setAttribute("aria-live", "polite");
		for (const [label, operation] of [
			["縮小", () => Math.max(100, zoom - 25)],
			["放大", () => Math.min(300, zoom + 25)],
			["適合寬度", () => 100],
		]) {
			const button = document.createElement("button");
			button.type = "button";
			button.textContent = label;
			button.addEventListener("click", () => {
				zoom = operation();
				output.textContent = `${zoom}%`;
				draw();
			});
			controls.append(button);
		}
		const expand = document.createElement("button");
		expand.type = "button";
		expand.textContent = "展開圖表";
		expand.addEventListener("click", () => {
			const placeholder = document.createComment(
				"diagram return position",
			);
			target.before(placeholder);
			const dialog = document.createElement("dialog");
			dialog.className = "ks-diagram-dialog";
			const header = document.createElement("div");
			header.className = "ks-dialog-header";
			const title = document.createElement("h2");
			title.id = `${id}-title`;
			title.textContent = "展開圖表";
			dialog.setAttribute("aria-labelledby", title.id);
			const close = document.createElement("button");
			close.type = "button";
			close.textContent = "關閉圖表";
			close.autofocus = true;
			close.addEventListener("click", () => dialog.close());
			header.append(title, close);
			dialog.append(header);
			document.body.append(dialog);
			const preserveFrame = typeof dialog.moveBefore === "function";
			if (preserveFrame) dialog.moveBefore(target, null);
			else dialog.append(target);
			expand.hidden = true;
			dialog.addEventListener(
				"close",
				() => {
					if (preserveFrame && placeholder.isConnected) {
						placeholder.parentElement.moveBefore(
							target,
							placeholder,
						);
						placeholder.remove();
					} else placeholder.replaceWith(target);
					expand.hidden = false;
					dialog.remove();
					if (!preserveFrame) draw();
					if (
						expand.isConnected &&
						!dialog.hasAttribute("data-navigating")
					)
						expand.focus({ preventScroll: true });
				},
				{ once: true },
			);
			dialog.showModal();
			// Preserve the iframe document when supported; older browsers need to reload srcdoc.
			if (!preserveFrame) draw();
		});
		const hint = document.createElement("p");
		hint.className = "ks-scroll-hint";
		hint.textContent =
			"100% 為適合寬度；放大後可在圖內水平捲動，或聚焦圖表後用方向鍵平移。";
		output.textContent = `${zoom}%`;
		controls.append(output, expand);
		target.append(controls, hint, frame);
		draw();
	} finally {
		workspace.remove();
		document.getElementById(`d${id}`)?.remove();
	}
}
